create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'student' check (role in ('student','admin')),
  premium_until timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  title text not null,
  language text not null,
  level text not null default 'Beginner',
  description text not null default '',
  content text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  plan text not null check (plan in ('1 herinandro','1 volana','1 taona')),
  amount_ariary integer not null check (amount_ariary in (1000,10000,50000)),
  method text not null check (method in ('Orange Money','MVola')),
  transaction_reference text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint payment_plan_amount_match check (
    (plan = '1 herinandro' and amount_ariary = 1000) or
    (plan = '1 volana' and amount_ariary = 10000) or
    (plan = '1 taona' and amount_ariary = 50000)
  )
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email)
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.lessons enable row level security;
alter table public.payments enable row level security;

-- SECURITY DEFINER helper avoids recursive profile-table RLS checks.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles for select to authenticated
using (auth.uid() = id or public.is_admin());
-- Users may not edit their own role or premium status. Admins may manage profile records.
drop policy if exists "Admins can update profiles" on public.profiles;
create policy "Admins can update profiles" on public.profiles for update to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Lessons are readable by signed-in users" on public.lessons;
create policy "Lessons are readable by signed-in users" on public.lessons for select to authenticated using (true);
drop policy if exists "Admins can manage lessons" on public.lessons;
create policy "Admins can manage lessons" on public.lessons for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Users can read own payments" on public.payments;
create policy "Users can read own payments" on public.payments for select to authenticated
using (user_id = auth.uid() or public.is_admin());
drop policy if exists "Users can submit own payment requests" on public.payments;
create policy "Users can submit own payment requests" on public.payments for insert to authenticated
with check (user_id = auth.uid() and status = 'pending');
drop policy if exists "Admins can review payments" on public.payments;
create policy "Admins can review payments" on public.payments for update to authenticated
using (public.is_admin()) with check (public.is_admin());

